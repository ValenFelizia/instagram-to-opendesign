import test from 'node:test';
import assert from 'node:assert/strict';
import { runEval } from '../evals/consumer-neutral-core/run.mjs';

// Mechanical layer for evals/consumer-neutral-core. The judgment layer lives in
// that case's outcome.md and is never asserted here. Assertion ids match case.json.
test('eval: consumer-neutral core reproduces the committed handoff without an adapter contract', async () => {
  const summary = await runEval();

  // EVAL-1: the core reaches a ready brief without a renderer.
  assert.equal(summary.briefStatus, 'ready-for-execution');

  // EVAL-2: the exported inventory is complete and verified against itself.
  assert.equal(summary.inventoryStatus, 'ready-for-execution');
  assert.equal(summary.inventoryMode, 'selected-execution');
  assert.equal(summary.entrypoint, 'START.md');
  assert.ok(summary.files.includes('START.md'));
  assert.ok(summary.files.includes('handoff.json'));
  assert.ok(summary.files.includes('design-brief.json'));

  // EVAL-3: every generated byte matches the committed public example.
  assert.deepEqual(summary.mismatched, []);
  assert.equal(summary.matchesCommittedExample, true);
  assert.deepEqual(summary.authored, ['README.md']);

  // EVAL-4: the same case exports the same inventory twice.
  assert.equal(summary.reproducible, true);

  // EVAL-5: no OpenDesign manifest, slot file or catalog reference leaks into the core output.
  assert.deepEqual(summary.leaks, []);
  assert.ok(!summary.files.includes('manifest.json'));
  assert.ok(!summary.files.includes('metadata.json'));
  assert.ok(!summary.files.includes('tokens.css'));

  // EVAL-6: the handoff declares its own schema and an entrypoint.
  assert.equal(summary.handoff.schemaVersion, 'agent-handoff/v1');
  assert.equal(summary.handoff.entrypoint, 'START.md');
});
